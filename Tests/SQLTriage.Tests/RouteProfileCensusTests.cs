/// <summary>
/// THE INVARIANT: <b>the set of routable pages in a build is EXACTLY the union of the route groups
/// whose owning module is compiled into that build.</b> A route present that no compiled module owns,
/// a route absent that a compiled module owns, and a route that no module owns at all each FAIL.
///
/// <para><b>WHY THIS EXISTS.</b> On 2026-09-14 a routable page, <c>/live</c>
/// (<c>Components/Dashboards/LiveDashboard.razor</c>), was found in the COMMUNITY (free) build.
/// <c>buildprofile.targets</c> decides which pages ship in each profile from a hand-maintained list of
/// Content Removes, and nothing derived from the code could notice that escape, or the next one. This
/// is the IP boundary between the free and the paid product.</para>
///
/// <para><b>WHAT "ROUTABLE" MEANS HERE.</b> A <c>Microsoft.AspNetCore.Components.RouteAttribute</c> in
/// the custom-attribute METADATA of a type in the LOADED PRODUCT ASSEMBLY, read with
/// <c>GetCustomAttributesData()</c> so no attribute is ever instantiated. Never a string search: a
/// byte search for <c>/live</c> also hits the community DLL wherever <c>/dashboard/live</c> appears
/// (nine hits when measured on 2026-09-14; the number moves with the build and nothing here asserts
/// it), and <c>Data/RouteConstants.cs</c> declares <c>Sessions = "/sessions"</c> unfenced by
/// design, so <c>/sessions</c> has a byte hit in a build where it is NOT a route (both PROVED
/// 2026-09-14). The specimen controls below hold the census to that distinction.</para>
///
/// <para><b>WHAT "COMPILED IN" MEANS HERE.</b> The product assembly's OWN <see cref="BuildModules"/>
/// constants, read off the loaded assembly by reflection (<c>FieldInfo.GetRawConstantValue()</c>).
/// Never a <c>#if</c> in this project: a symbol answers about the TEST project's compilation, and the
/// question is about the assembly under test. The values this project inlined at compile time are
/// compared with the reflected ones, and a disagreement fails (the stale <c>bin/</c> trap).</para>
///
/// <para><b>PROVENANCE OF THE APPROVED TABLE.</b> <see cref="ApprovedRouteTable"/> was generated by
/// script, not typed, from a route-to-module table derived STRUCTURALLY from the
/// <c>buildprofile.targets</c> XML item tree plus the <c>@page</c> literals, measured at
/// <c>18f5171958c87ebae90d6e18788534b53f8f4c65</c> on 2026-09-17 by lane
/// <c>page-route-profile-census</c>; evidence is filed in the project's private evidence archive at
/// <c>evidence/page-route-profile-census-2026-09-17/</c>. At that commit its Core group equalled the
/// route set of a real community build exactly, so the XML model was faithful. ONE ruling was applied
/// on top of the measurement: <c>/live</c> moves from Core to LiveMonitoring. The result is 91 routes:
/// Core 42, Premium 8, DevTools 10, Portal 3, Operations 11, LiveMonitoring 16, PerfReport 1. Those
/// counts are recorded here as provenance and are deliberately NOT asserted: every verdict in this
/// class compares SETS.</para>
///
/// <para><b>OWNERSHIP IS A RULING, NOT AN INFERENCE.</b> Which edition sells a page is a commercial
/// decision. When a fact here fails, the failure text names what to CHECK; it never names an edit,
/// because the attractive repair (move the route into whichever group makes the test pass) is exactly
/// how the boundary would be moved without anyone deciding to move it.</para>
///
/// <para><b>WHO RUNS THIS.</b> The automatic runner is CI, which builds and tests the COMMUNITY profile
/// on pushes to main and on pull requests (.github/workflows/build.yml; a push to a lane branch alone
/// runs nothing), so the community mode is the one that fires unattended. The full-profile mode is
/// what a developer runs locally; <see cref="F5_a_full_build_predicts_the_community_route_set_the_table_approves"/>
/// exists so that a page escaping community is also caught there.</para>
///
/// <para><b>IT FAILS; IT NEVER SKIPS.</b> A module combination with no frozen expectation is refused
