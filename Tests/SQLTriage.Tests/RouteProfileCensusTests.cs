    // ── F4: specimen controls ──────────────────────────────────────────────────────────────────

    /// <summary>
    /// ⚠ THESE ARE SPECIMEN CONTROLS, NOT THE GUARANTEE. The guarantee is F1-F3, which enumerate from
    /// the compiled assembly. Naming a handful of routes cannot prove a set; these only fail loudly
    /// when the instrument stops discriminating: blind to routes, reading route CONSTANTS as if they
    /// were routes, or collapsing a type that declares two routes into one.
    /// </summary>
    [Fact]
    public void F4_specimen_controls_discriminate_routes_from_constants_and_types_from_routes()
    {
        var modules = RequireModuleFlagsWithAFrozenExpectation();
        var census = RequireALiveHaystack();
        var present = new HashSet<string>(census.Rows.Select(r => r.Route), StringComparer.Ordinal);

        // SPECIMEN CONTROL, NOT THE GUARANTEE: two Core pages are present in every build.
        foreach (var everyBuild in new[] { "/settings", "/servers" })
        {
            var everyBuildRoutable = present.Contains(everyBuild);
            Assert.True(everyBuildRoutable,
                "SPECIMEN CONTROL, NOT THE GUARANTEE: " + everyBuild + " is a Core page and must be routable "
                + "in every build, and it is absent from this " + modules.Edition + " build. WHAT TO CHECK: "
                + "whether the census is reading RouteAttribute data at all before believing any other result.");
        }

        // SPECIMEN CONTROL, NOT THE GUARANTEE: a route CONSTANT is not a route.
        var routeConstants = Product.GetType("SQLTriage.Data.RouteConstants", throwOnError: false);
        Assert.True(routeConstants != null,
            "SPECIMEN CONTROL, NOT THE GUARANTEE: SQLTriage.Data.RouteConstants is not in the product "
            + "assembly, so the constants-are-not-routes control has no subject. WHAT TO CHECK: whether it "
            + "was renamed or moved; a control whose subject silently vanished reads exactly like a pass.");
        var sessionsConstants = routeConstants!
            .GetFields(BindingFlags.Public | BindingFlags.Static)
            .Where(f => f.IsLiteral && f.FieldType == typeof(string) && (string?)f.GetRawConstantValue() == "/sessions")
            .Select(f => f.Name).ToList();
        _out.WriteLine($"RouteConstants literal fields whose value is /sessions: [{string.Join(", ", sessionsConstants)}]; "
                     + $"/sessions routable={present.Contains("/sessions")}; LiveMonitoring={modules.Flags["LiveMonitoring"]}");
        Assert.True(sessionsConstants.Count > 0,
            "SPECIMEN CONTROL, NOT THE GUARANTEE: no const string field on RouteConstants has the value "
            + "/sessions in this build, so this control can no longer show that a route CONSTANT is not "
            + "read as a route. WHAT TO CHECK: whether that constant was fenced or renamed, and whether "
            + "any other unfenced route constant still names a page that is compiled out of community.");
        var sessionsRoutable = present.Contains("/sessions");
        if (!modules.Flags["LiveMonitoring"])
            Assert.True(!sessionsRoutable,
                "SPECIMEN CONTROL, NOT THE GUARANTEE: LiveMonitoring is compiled out, the constant "
                + "RouteConstants." + sessionsConstants[0] + " = /sessions is in the assembly, and /sessions "
                + "was reported as a ROUTE. Either the census is reading string constants rather than "
                + "RouteAttribute metadata, or Pages/Sessions.razor shipped. WHAT TO CHECK: the declaring "
                + "type printed for /sessions in F0's output.");
        else
            Assert.True(sessionsRoutable,
                "SPECIMEN CONTROL, NOT THE GUARANTEE: LiveMonitoring is compiled in and /sessions is not "
                + "routable. WHAT TO CHECK: Pages/Sessions.razor and its @page directives.");

        // SPECIMEN CONTROL, NOT THE GUARANTEE: a census of TYPES is not a census of ROUTES.
        var multiRouteTypes = census.Rows.GroupBy(r => r.TypeName, StringComparer.Ordinal)
            .Where(g => g.Count() > 1).Select(g => g.Key).OrderBy(s => s, StringComparer.Ordinal).ToList();
        _out.WriteLine($"routed types declaring more than one route: [{string.Join(", ", multiRouteTypes)}]");
        foreach (var name in new[] { "SQLTriage.Pages.Pmemory", "SQLTriage.Pages.Sessions" })
        {
            var typePresent = Product.GetType(name, throwOnError: false) != null;
            _out.WriteLine($"    {name} present={typePresent}");
            Assert.True(typePresent == modules.Flags["LiveMonitoring"],
                "SPECIMEN CONTROL, NOT THE GUARANTEE: type " + name + " present=" + typePresent + " while "
                + "LiveMonitoring=" + modules.Flags["LiveMonitoring"] + ". WHAT TO CHECK: whether the page was "
                + "renamed (the two-route control names it) or whether its module gate changed.");
        }
        var expectedMultiRoute = modules.Flags["LiveMonitoring"]
            ? new List<string> { "SQLTriage.Pages.Pmemory", "SQLTriage.Pages.Sessions" }
            : new List<string>();
        Assert.True(multiRouteTypes.SequenceEqual(expectedMultiRoute, StringComparer.Ordinal),
            "SPECIMEN CONTROL, NOT THE GUARANTEE: expected exactly [" + string.Join(", ", expectedMultiRoute)
            + "] to declare more than one route (Pmemory: /pmemory and /memory; Sessions: /sessions and "
            + "/dashboard/sessions, both LiveMonitoring pages), and measured [" + string.Join(", ", multiRouteTypes)
            + "]. If the two-route pages vanished while LiveMonitoring is on, the census may be collapsing "
            + "a type's routes into one. WHAT TO CHECK: the per-type route rows in F0's output, and the "
            + "@page directives of the named pages.");

        // SPECIMEN CONTROL, NOT THE GUARANTEE: the opt-in PerfReport page follows its flag both ways.
