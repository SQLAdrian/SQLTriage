    // ── F5: the full-profile predictor ─────────────────────────────────────────────────────────

    /// <summary>
    /// So that a page escaping COMMUNITY is also caught by a FULL-profile run, which is the run a
    /// developer makes locally.
    ///
    /// <para>⚠ THIS IS A MODEL OF MSBUILD ITEM EVALUATION — a tripwire over the buildprofile.targets
    /// XML, NOT THE GUARANTEE. It predicts which routed types a community build keeps by asking
    /// <see cref="ProfileGateModel"/> which <c>.razor</c> files the community profile Content-Removes,
    /// and mapping each file to a type by Razor's folder-to-namespace convention. MSBuild's real
    /// evaluation can differ from that model (a condition the model does not parse, an
    /// <c>@namespace</c> override, an item removed by a mechanism other than this file). The GUARANTEE
    /// is <see cref="F2_no_route_is_present_whose_owning_module_is_compiled_out"/> run in a real
    /// community build, which CI runs on pushes to main and on pull requests.</para>
    ///
    /// <para>In a community build this still runs, predicting only over the types present.</para>
    /// </summary>
    [Fact]
    public void F5_a_full_build_predicts_the_community_route_set_the_table_approves()
    {
        var modules = RequireModuleFlagsWithAFrozenExpectation();
        var census = RequireALiveHaystack();
        var table = ApprovedTable();
        var root = RawPassedScan.RepoRoot();

        var surface = ProfileGateModel.CommunitySurface(root);
        var removedTypes = new HashSet<string>(
            ProfileGateModel.QualifiedTypeNamesFromRemovedPages(surface.RemovedPages), StringComparer.Ordinal);
        Dump("MODEL: .razor files the community profile Content-Removes", surface.RemovedPages);

        // MODEL SPECIMEN CONTROLS, NOT THE GUARANTEE, both ways.
        Assert.True(removedTypes.Contains("SQLTriage.Pages.Sessions"),
            "MODEL SPECIMEN CONTROL, NOT THE GUARANTEE: the model of buildprofile.targets does not remove "
            + "SQLTriage.Pages.Sessions from a community build, but live-monitoring is off in community. "
            + "The model has stopped reading the item tree, so its prediction below is worthless. WHAT TO "
            + "CHECK: ProfileGateModel.CommunitySurface against the live-monitoring ItemGroup.");
        Assert.True(!removedTypes.Contains("SQLTriage.Pages.Settings"),
            "MODEL SPECIMEN CONTROL, NOT THE GUARANTEE: the model removes SQLTriage.Pages.Settings, a Core "
            + "page, from community. The model is over-removing, so its prediction below is worthless. "
            + "WHAT TO CHECK: ProfileGateModel's condition parsing against buildprofile.targets.");

        // The model's evaluated module switches for community.
        var evaluation = ProfileGateModel.Evaluate(root, new Dictionary<string, string>
        {
            ["SQLTriageProfile"] = "community",
            ["SQLTriagePrivate"] = "",
        });
        bool ModelTurnsOn(string excludeProperty) =>
            !(evaluation.Properties.TryGetValue(excludeProperty, out var v)
              && string.Equals(v, "true", StringComparison.OrdinalIgnoreCase));
        var modelOperationsOn = ModelTurnsOn("SQLTExcludeOperations");
        var modelLiveMonitoringOn = ModelTurnsOn("SQLTExcludeLiveMonitoring");
        _out.WriteLine($"MODEL community module switches: Operations={modelOperationsOn} LiveMonitoring={modelLiveMonitoringOn}");

        if (modules.Flags["Community"])
        {
            // In a real community build the model's switches can be checked against the real ones.
            Assert.True(modelOperationsOn == modules.Flags["Operations"]
                        && modelLiveMonitoringOn == modules.Flags["LiveMonitoring"],
                "MODEL CONTROL: the model of buildprofile.targets evaluates community as Operations="
                + modelOperationsOn + " LiveMonitoring=" + modelLiveMonitoringOn + ", but this real community "
                + "build carries BuildModules.Operations=" + modules.Flags["Operations"]
                + " LiveMonitoring=" + modules.Flags["LiveMonitoring"] + ". WHAT TO CHECK: buildprofile.json's "
                + "module toggles against what ProfileGateModel.Evaluate reads from it.");
        }

        // Every routed type must map to exactly one .razor file by the folder-to-namespace convention,
        // or the model cannot say whether that type is removed.
        var razorByType = RazorFilesByQualifiedTypeName(root);
        var routedTypes = census.Rows.Select(r => r.TypeName).Distinct(StringComparer.Ordinal).ToList();
        var unmapped = routedTypes
            .Where(t => !razorByType.TryGetValue(t, out var files) || files.Count != 1)
            .Select(t => t + " -> [" + string.Join(", ", razorByType.TryGetValue(t, out var files) ? files : new List<string>()) + "]")
            .ToList();
        Dump("routed types that do not map to exactly one .razor file", unmapped);
        Assert.True(unmapped.Count == 0,
            "these routed types do not map to exactly one .razor file under the folder-to-namespace "
            + "convention, so the model cannot predict whether a community build keeps them: "
            + string.Join(" | ", unmapped) + ". WHAT TO CHECK: an @namespace override in the page, a page "
            + "declared outside a .razor file, or two files that map to one type name.");

        var approvedCommunity = new HashSet<string>(
            ApprovedRouteTable
                .Where(r => r.Group == CoreGroup
                            || (r.Group == "Operations" && modelOperationsOn)
                            || (r.Group == "LiveMonitoring" && modelLiveMonitoringOn))
                .Select(r => r.Route),
            StringComparer.Ordinal);
        var predictedRows = census.Rows.Where(r => !removedTypes.Contains(r.TypeName)).ToList();
        var predicted = new HashSet<string>(predictedRows.Select(r => r.Route), StringComparer.Ordinal);

        Dump("MODEL: community route set predicted from this " + modules.Edition + " build",
             predictedRows.Select(r => r.Route + "  " + r.TypeName));
        Dump("APPROVED: community route set from the table", approvedCommunity);

        var wouldEscape = predictedRows.Where(r => !approvedCommunity.Contains(r.Route)).ToList();
        var wouldVanish = approvedCommunity.Where(r => !predicted.Contains(r)).ToList();
        Dump("predicted in community but NOT approved", wouldEscape.Select(r => r.Route + "  " + r.TypeName));
        Dump("approved for community but NOT predicted", wouldVanish);

        Assert.True(wouldEscape.Count == 0 && wouldVanish.Count == 0,
            string.Join(" ", wouldEscape.Select(r =>
            {
                if (!table.TryGetValue(r.Route, out var owner))
                    return "route " + r.Route + " (type " + r.TypeName + ") would ship in a community build "
                         + "according to the model of buildprofile.targets, and appears in no module group of "
                         + "the approved route table (F1 reports the same route). WHAT TO CHECK: which module "
                         + "this page belongs to, and whether buildprofile.targets removes it in every profile "
                         + "where that module is off.";
                return "route " + r.Route + " (type " + r.TypeName + ") would ship in a community build "
                     + "according to the model of buildprofile.targets, but the approved route table assigns "
                     + "it to " + owner.Group + ", which community compiles out. WHAT TO CHECK: whether "
                     + owner.File + " is removed by the ItemGroup for " + owner.Group + " in "
                     + "buildprofile.targets, and whether this page is meant to ship in the community edition.";
            }))
            + string.Join(" ", wouldVanish.Select(route =>
                " route " + route + " is approved for the community edition, but the model of "
                + "buildprofile.targets predicts no type in this build keeps it. WHAT TO CHECK: first, whether "
                + "this route's module group in the approved table was changed without a recorded ruling (a "
                + "retagged row makes a correct Content Remove look like a mistake); then whether its "
                + "page is Content-Removed by a community ItemGroup by mistake, or renamed or deleted."))
            + " (This verdict is a MODEL; the guarantee is F2 in a real community build.)");
    }

    /// <summary>
    /// Every <c>.razor</c> file in the app tree, keyed by the type name Razor generates for it. Skips
    /// the test tree and build output (<c>bin</c>, <c>obj</c>) and dot-directories, where copies of the
    /// app's markup are staged for other tests and would otherwise make every page map to two files.
    /// It walks DISK, not git's tracked list, deliberately: MSBuild's default Razor item glob reads disk
    /// too, so an untracked page MSBuild would compile is seen here, and a stray untracked copy of a
    /// routed page makes its type map to two files, which F5 fails on by name.
    /// </summary>
    private static IReadOnlyDictionary<string, List<string>> RazorFilesByQualifiedTypeName(DirectoryInfo root)
    {
        var byType = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        var pending = new Stack<DirectoryInfo>();
        pending.Push(root);
        while (pending.Count > 0)
        {
            var dir = pending.Pop();
            foreach (var sub in dir.EnumerateDirectories())
            {
                var n = sub.Name;
                if (n.StartsWith(".", StringComparison.Ordinal)) continue;
                if (string.Equals(n, "bin", StringComparison.OrdinalIgnoreCase)) continue;
                if (string.Equals(n, "obj", StringComparison.OrdinalIgnoreCase)) continue;
                if (string.Equals(n, "node_modules", StringComparison.OrdinalIgnoreCase)) continue;
                if (dir.FullName == root.FullName && string.Equals(n, "Tests", StringComparison.OrdinalIgnoreCase)) continue;
                pending.Push(sub);
            }
            foreach (var file in dir.EnumerateFiles("*.razor"))
            {
                var rel = ProfileGateModel.Rel(root, file.FullName);
                var typeName = QualifiedTypeNameOf(rel);
                if (!byType.TryGetValue(typeName, out var list)) byType[typeName] = list = new List<string>();
                list.Add(rel);
            }
        }
        return byType;
    }
