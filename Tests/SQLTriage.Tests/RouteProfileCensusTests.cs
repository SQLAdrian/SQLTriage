    // ── F1: every present route has an owner ───────────────────────────────────────────────────

    /// <summary>How the NEXT new page is caught, in ANY profile: a route no group owns fails here.</summary>
    [Fact]
    public void F1_every_route_in_the_build_is_owned_by_a_group_in_the_approved_table()
    {
        var modules = RequireModuleFlagsWithAFrozenExpectation();
        var census = RequireALiveHaystack();
