            "SPECIMEN CONTROL, NOT THE GUARANTEE: /performance-report routable="
            + present.Contains("/performance-report") + " but BuildModules.PerfReport=" + modules.Flags["PerfReport"]
            + ". It must be present exactly when -p:SQLTriagePrivate=true built a non-community profile. "
            + "WHAT TO CHECK: the SQLTPerfReport ItemGroup in buildprofile.targets and how this build was invoked.");

