    // ── The instrument ─────────────────────────────────────────────────────────────────────────

    private sealed record RouteRow(string Route, string TypeName);

    private sealed record RouteCensus(
        string AssemblySimpleName,
        string AssemblyVersion,
        int TypeCount,
        IReadOnlyList<string> TypeLoadFailures,
        IReadOnlyList<string> AttributeReadFailures,
        IReadOnlyList<string> ForeignRouteAttributes,
        IReadOnlyList<RouteRow> Rows);

    private static readonly Lazy<RouteCensus> Census = new(ReadRouteCensus);

    /// <summary>
    /// Enumerates every route template from RouteAttribute METADATA on the product assembly's types.
    /// Nothing is instantiated and no app code runs. A type that cannot be loaded, or whose attribute
    /// data cannot be read, is RECORDED rather than skipped, because an unreadable type is invisible to
    /// every verdict below and would read as a pass.
    /// </summary>
    private static RouteCensus ReadRouteCensus()
    {
        var product = Product;
        var typeLoadFailures = new List<string>();
        Type?[] types;
        try
        {
            types = product.GetTypes();
        }
        catch (ReflectionTypeLoadException ex)
        {
            types = ex.Types;
            foreach (var loaderException in ex.LoaderExceptions)
                if (loaderException != null)
                    typeLoadFailures.Add(loaderException.GetType().Name + ": " + loaderException.Message);
            var unloaded = types.Count(t => t == null);
            typeLoadFailures.Add(unloaded + " type(s) could not be loaded (ReflectionTypeLoadException)");
        }

        var attributeReadFailures = new List<string>();
        var foreign = new List<string>();
        var rows = new List<RouteRow>();

        foreach (var type in types)
        {
            if (type is null) continue;
            var typeName = type.FullName ?? type.Name;

            IList<CustomAttributeData> data;
            try
            {
                data = type.GetCustomAttributesData();
            }
            catch (Exception ex)
            {
                attributeReadFailures.Add(typeName + ": " + ex.GetType().Name + ": " + ex.Message);
                continue;
            }

            foreach (var attribute in data)
            {
                string? attributeFullName;
                string attributeSimpleName;
                try
                {
                    attributeFullName = attribute.AttributeType.FullName;
                    attributeSimpleName = attribute.AttributeType.Name;
                }
                catch (Exception ex)
                {
                    attributeReadFailures.Add(typeName + ": attribute type unreadable: "
                                              + ex.GetType().Name + ": " + ex.Message);
                    continue;
                }

                if (string.Equals(attributeFullName, RouteAttributeFullName, StringComparison.Ordinal))
                {
                    var template = attribute.ConstructorArguments.Count == 1
                        ? attribute.ConstructorArguments[0].Value as string
                        : null;
                    if (string.IsNullOrWhiteSpace(template))
                        attributeReadFailures.Add(typeName
                            + ": RouteAttribute without exactly one non-empty string template argument");
                    else
                        rows.Add(new RouteRow(template, typeName));
                }
                else if (string.Equals(attributeSimpleName, "RouteAttribute", StringComparison.Ordinal))
                {
                    foreign.Add(typeName + " carries " + (attributeFullName ?? attributeSimpleName));
                }
            }
        }

        var name = product.GetName();
        return new RouteCensus(
            name.Name ?? "",
            name.Version?.ToString() ?? "",
            types.Count(t => t != null),
            typeLoadFailures,
            attributeReadFailures,
            foreign,
            rows.OrderBy(r => r.Route, StringComparer.Ordinal)
                .ThenBy(r => r.TypeName, StringComparer.Ordinal).ToList());
    }

    // ── The module flags ───────────────────────────────────────────────────────────────────────

    /// <summary>What THIS test project was compiled against: the constants are inlined here at
    /// compile time, so these values describe the reference the test project saw, not the assembly
    /// the test host loaded.</summary>
    private static IReadOnlyDictionary<string, bool> CompiledModuleFlags() =>
        new Dictionary<string, bool>(StringComparer.Ordinal)
        {
            ["Community"] = BuildModules.Community,
            ["Premium"] = BuildModules.Premium,
            ["DevTools"] = BuildModules.DevTools,
            ["Portal"] = BuildModules.Portal,
            ["Operations"] = BuildModules.Operations,
            ["LiveMonitoring"] = BuildModules.LiveMonitoring,
            ["PerfReport"] = BuildModules.PerfReport,
        };

    /// <summary>What the LOADED product assembly says, read off its metadata. Null = the constant is
    /// missing or is not a literal bool, which is itself a failure.</summary>
    private static IReadOnlyDictionary<string, bool?> ProductModuleFlags()
    {
        var flags = new Dictionary<string, bool?>(StringComparer.Ordinal);
        foreach (var flagName in ModuleFlagNames)
        {
            var field = typeof(BuildModules).GetField(flagName, BindingFlags.Public | BindingFlags.Static);
            flags[flagName] = field is { IsLiteral: true } && field.GetRawConstantValue() is bool b ? b : null;
        }
        return flags;
    }

    /// <summary>
    /// The module flags this census reasons with, after the configuration has been proved
    /// trustworthy. Called FIRST by every fact that reasons with module flags, which is every fact
    /// except F0_the_census_reads_a_live_product_assembly_before_any_verdict (it reads routes only).
    /// One definition, not a copy per fact,
    /// so a fact added later either calls it or says at its own body why it does not.
    /// </summary>
    private sealed record ModuleContext(IReadOnlyDictionary<string, bool> Flags)
    {
        public bool IsCompiledIn(string group) =>
            group == CoreGroup || (Flags.TryGetValue(group, out var on) && on);

        public string Edition =>
            Flags["Community"] ? "community" : Flags["PerfReport"] ? "full+private" : "full";
    }

    private ModuleContext RequireModuleFlagsWithAFrozenExpectation()
    {
        var compiled = CompiledModuleFlags();
        var reflected = ProductModuleFlags();

        foreach (var flagName in ModuleFlagNames)
            _out.WriteLine($"BuildModules.{flagName}: product(reflected)={Show(reflected[flagName])} "
                         + $"test-project(inlined)={compiled[flagName]}");

        var disagreeing = ModuleFlagNames
            .Where(n => reflected[n] != compiled[n])
            .Select(n => $"{n}: product={Show(reflected[n])} test-project={compiled[n]}")
            .ToList();

        Assert.True(disagreeing.Count == 0,
            "THE PRODUCT ASSEMBLY AND THIS TEST PROJECT DISAGREE ABOUT WHICH MODULES ARE COMPILED IN, so "
            + "nothing this class reports is evidence about either of them. Disagreeing flags: "
            + string.Join("; ", disagreeing) + ". The product value is read off the SQLTriage.dll the "
            + "test host actually loaded; the test-project value was inlined when this test assembly "
            + "was compiled. bin/ carries the LAST profile built, so a test assembly and a product "
            + "assembly from two different builds land here. WHAT TO CHECK: that the test assembly and "
            + "the product assembly came from the same -p:SQLTriageProfile build (and the same "
            + "-p:SQLTriagePrivate value), by the timestamps and paths of both DLLs, before reading any "
            + "other result in this class.");

        var flags = ModuleFlagNames.ToDictionary(n => n, n => reflected[n]!.Value, StringComparer.Ordinal);

        var communityShape = !flags["Premium"] && !flags["DevTools"] && !flags["Portal"] && !flags["PerfReport"];
        var fullShape = flags["Premium"] && flags["DevTools"] && flags["Portal"]
                        && flags["Operations"] && flags["LiveMonitoring"];
        var holds = flags["Community"] ? communityShape : fullShape;

        Assert.True(holds,
            "THIS MODULE COMBINATION HAS NO FROZEN EXPECTATION, so this census refuses to report on it "
            + "rather than skip. Flags: " + string.Join(", ", ModuleFlagNames.Select(n => n + "=" + flags[n]))
            + ". The expectations were frozen for two shapes only: Community=true implies Premium, "
            + "DevTools, Portal and PerfReport are all false; Community=false implies Premium, DevTools, "
            + "Portal, Operations and LiveMonitoring are all true. WHAT TO CHECK: how this assembly was "
            + "built (which -p: properties reached buildprofile.targets), and whether a new profile shape "
            + "was introduced on purpose. A new shape is a decision about what that edition sells, and "
            + "this census has no approved answer for it yet.");

        return new ModuleContext(flags);
    }

    private static string Show(bool? value) => value.HasValue ? value.Value.ToString() : "MISSING-OR-NOT-A-BOOL-LITERAL";

    // ── Haystack control ───────────────────────────────────────────────────────────────────────

    /// <summary>
    /// Asserted BEFORE any needle, by every fact that reads routes, which is every fact except
    /// F0_the_module_flags_are_read_off_the_product_and_agree_with_the_test_build (it reads module flags
    /// only). Every verdict below is vacuously green over an empty
    /// or unreadable assembly, so an empty haystack is a failure, never a pass.
    /// </summary>
    private RouteCensus RequireALiveHaystack()
    {
        var census = Census.Value;
        _out.WriteLine($"product assembly {census.AssemblySimpleName} {census.AssemblyVersion} at "
                     + Product.Location);
        _out.WriteLine($"types={census.TypeCount} route-rows={census.Rows.Count} "
                     + $"routed-types={census.Rows.Select(r => r.TypeName).Distinct().Count()} "
                     + $"type-load-failures={census.TypeLoadFailures.Count} "
                     + $"attribute-read-failures={census.AttributeReadFailures.Count} "
                     + $"foreign-RouteAttribute={census.ForeignRouteAttributes.Count}");

        Assert.True(census.AssemblySimpleName == "SQLTriage",
            "the assembly that owns BuildModules is named '" + census.AssemblySimpleName + "', not "
            + "SQLTriage. WHAT TO CHECK: whether BuildModules moved to another assembly; this census reads "
            + "routes from the assembly that owns it.");

        Assert.True(census.TypeCount > 1000,
            "the product assembly yielded only " + census.TypeCount + " loadable types; a real SQLTriage "
            + "build carries thousands. LIVENESS FLOOR, not a frozen count. WHAT TO CHECK: whether the "
            + "right assembly was loaded and whether type loading failed wholesale.");

        Assert.True(census.Rows.Count > 0,
            "the product assembly yielded ZERO RouteAttribute rows, so every fact in this class would pass "
            + "over nothing. WHAT TO CHECK: whether the attribute's full name is still "
            + RouteAttributeFullName + " and whether the attribute data could be read at all.");

        Assert.True(census.TypeLoadFailures.Count == 0,
            "types in the product assembly could not be loaded, and an unloadable type is invisible to "
            + "this census, so a route on it would be neither caught nor counted: "
            + string.Join(" | ", census.TypeLoadFailures) + ". WHAT TO CHECK: which dependency failed to "
            + "load in the test host.");

        Assert.True(census.AttributeReadFailures.Count == 0,
            "custom attribute data could not be read for these types, so their routes are unknown: "
            + string.Join(" | ", census.AttributeReadFailures) + ". WHAT TO CHECK: the named types and "
            + "the assemblies their attributes come from.");

        Assert.True(census.ForeignRouteAttributes.Count == 0,
            "types carry an attribute named RouteAttribute that is NOT " + RouteAttributeFullName
            + ": " + string.Join(" | ", census.ForeignRouteAttributes) + ". This census reads only the "
            + "Blazor attribute. WHAT TO CHECK: whether these types are routable by some other router, in "
            + "which case this census is blind to them.");

        return census;
    }

    // ── The approved table, validated before use ───────────────────────────────────────────────

    private static IReadOnlyDictionary<string, (string Group, string File)> ApprovedTable()
    {
        var duplicates = ApprovedRouteTable.GroupBy(r => r.Route, StringComparer.Ordinal)
            .Where(g => g.Count() > 1).Select(g => g.Key).OrderBy(s => s, StringComparer.Ordinal).ToList();
        Assert.True(duplicates.Count == 0,
            "the approved route table names these routes more than once, so their ownership is ambiguous: "
            + string.Join(", ", duplicates) + ". WHAT TO CHECK: which module each page belongs to.");

        var unknownGroups = ApprovedRouteTable.Where(r => !RouteGroups.Contains(r.Group, StringComparer.Ordinal))
            .Select(r => r.Route + " -> " + r.Group).ToList();
        Assert.True(unknownGroups.Count == 0,
            "the approved route table uses groups that are not Core or a BuildModules flag: "
            + string.Join(", ", unknownGroups) + ". WHAT TO CHECK: the group names against "
            + "Data/BuildModules.cs.");

        return ApprovedRouteTable.ToDictionary(r => r.Route, r => (r.Group, r.File), StringComparer.Ordinal);
    }

    private void Dump(string title, IEnumerable<string> lines)
    {
        var sorted = lines.OrderBy(s => s, StringComparer.Ordinal).ToList();
        _out.WriteLine($"{title} (n={sorted.Count}):");
        foreach (var line in sorted) _out.WriteLine("    " + line);
    }

